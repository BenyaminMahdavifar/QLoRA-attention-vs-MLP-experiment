"""### 9. Comparative Analysis: Old (Base) vs Fine-Tuned Model
Let's evaluate and compare the responses generated by the original model (without adapters/fine-tuning) against the fine-tuned model (with active LoRA adapters) on a few samples from the validation/test set.
"""

import numpy as np
import torch

# Helper function to generate prediction
def generate_response(model_obj, tokenizer_obj, question):
    prompt = f"<s>[INST] Question: {question} [/INST] Answer:"
    inputs = tokenizer_obj(prompt, return_tensors="pt").to("cuda")

    with torch.no_grad():
        outputs = model_obj.generate(
            **inputs,
            max_new_tokens=100,
            temperature=0.7,
            do_sample=True,
            pad_token_id=tokenizer_obj.pad_token_id
        )

    decoded = tokenizer_obj.decode(outputs[0], skip_special_tokens=True)
    # Extract answer part after the prompt
    if "[/INST]" in decoded:
        return decoded.split("[/INST]")[-1].strip()
    return decoded

# Let's perform a quantitative benchmarking over the validation/test subset
eval_subset = dataset['validation'].select(range(min(15, len(dataset['validation']))))

base_scores = []
ft_scores = []

print("Starting Benchmark Evaluation on subset...")

# We will use simple exact/substring match and character-level similarity as basic metrics
def calculate_similarity(pred, ref):
    pred_clean = str(pred).strip().lower()
    ref_clean = str(ref).strip().lower()
    # Check for exact match or overlap
    if ref_clean in pred_clean or pred_clean in ref_clean:
        return 1.0
    return 0.0

for i, sample in enumerate(eval_subset):
    q = sample['Question']
    ref_ans = sample['Final answer']

    # 1. Base Model Answer (Disable adapters)
    peft_model.base_model.disable_adapter_layers()
    base_ans = generate_response(peft_model, tokenizer, q)

    # 2. Fine-Tuned Model Answer (Re-enable adapters)
    peft_model.base_model.enable_adapter_layers()
    ft_ans = generate_response(peft_model, tokenizer, q)

    # Evaluate metrics
    base_score = calculate_similarity(base_ans, ref_ans)
    ft_score = calculate_similarity(ft_ans, ref_ans)

    base_scores.append(base_score)
    ft_scores.append(ft_score)

    print(f"Sample {i+1} evaluated.")

# Print final benchmarking comparison metrics
print("\n================ BENCHMARK RESULT ================")
print(f"Base Model Accuracy (Overlap Match): {np.mean(base_scores) * 100:.2f}%")
print(f"Fine-tuned Model Accuracy (Overlap Match): {np.mean(ft_scores) * 100:.2f}%")
