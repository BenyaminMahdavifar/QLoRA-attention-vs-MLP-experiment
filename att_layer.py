"""### 6. Load Model with NF4 Quantization and Setup LoRA
We set up `BitsAndBytesConfig` for NF4 4-bit quantization, load the GPT-2 model, prepare it for PEFT training, and wrap it with a LoRA config.
"""

import torch
from transformers import AutoModelForCausalLM, BitsAndBytesConfig
from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training

# Configure NF4 quantization
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_use_double_quant=True,
    bnb_4bit_compute_dtype=torch.bfloat16
)

# Load 4-bit model with correct dtype mapping
model_quant = AutoModelForCausalLM.from_pretrained(
    model,
    quantization_config=bnb_config,
    device_map="auto",
    torch_dtype=torch.bfloat16
)

# Prepare model for PEFT training
model_quant = prepare_model_for_kbit_training(model_quant)

# Configure LoRA for Mistral-style architecture (q_proj, k_proj, v_proj, o_proj, gate_proj, up_proj, down_proj)
peft_config = LoraConfig(
    r=12,
    lora_alpha=4,
    target_modules=['q_proj' , 'k_proj' , 'v_proj' , 'o_proj'] ,
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM"
)

peft_model = get_peft_model(model_quant, peft_config)
peft_model.print_trainable_parameters()

"""### 7. Fine-tune the Model with Trainer
We configure training arguments integration with W&B and train the model.
"""

from transformers import TrainingArguments, Trainer, DataCollatorForLanguageModeling

training_args = TrainingArguments(
    output_dir="./Qwen3-0.6B-gaia-fine-tuned-att",
    per_device_train_batch_size=1, # Keep small due to 3B model memory footprint in 4-bit
    gradient_accumulation_steps=8,
    eval_strategy="steps",
    eval_steps=10,
    logging_steps=5,
    max_steps=50,
    learning_rate=1e-4, # Slightly lower learning rate for instruct model fine-tuning
    bf16=True,
    report_to="wandb",
    run_name="Qwen3-0.6B-gaia-fine-tuned-att",
    save_strategy="no"
)

trainer = Trainer(
    model=peft_model,
    args=training_args,
    train_dataset=final_splits['train'],
    eval_dataset=final_splits['validation'],
    data_collator=DataCollatorForLanguageModeling(tokenizer, mlm=False)
)

trainer.train()
